/**
 * Normalizes Quranic Uthmani Arabic text for smart fuzzy/stem search:
 * - Strips Uthmani diacritics, harakat, tatweel, small alef (\u0670), and ornamental brackets
 * - Unifies Alef variants (أ إ آ ٱ -> ا), Ta-Marbuta (ة -> ه), and Alef Maqsura (ى -> ي)
 */
export function normalizeQuranicText(text: string): string {
  if (!text) return '';
  return text
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '')
    .replace(/[﴿﴾()[\]•.,؛،؟!ـ]/g, ' ')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, ' ')
    .trim();
}

function stripArabicPrefix(normWord: string): string {
  if (normWord.length <= 3) return normWord;
  if (normWord.startsWith('وال') || normWord.startsWith('فال') || normWord.startsWith('بال') || normWord.startsWith('كال')) {
    return normWord.slice(3);
  }
  if (normWord.startsWith('ال') || normWord.startsWith('لل')) {
    return normWord.slice(2);
  }
  if (
    (normWord.startsWith('و') ||
      normWord.startsWith('ف') ||
      normWord.startsWith('ب') ||
      normWord.startsWith('ل')) &&
    normWord.length >= 4
  ) {
    return normWord.slice(1);
  }
  return normWord;
}

/**
 * Smart search algorithm over MUTASHABIHAT_DB:
 * Matches by exact (surahId, ayahNumber), by clicked Quranic word (with stem/prefix normalization),
 * by full Ayah text overlap, or by free-text teacher search query.
 */
export function findMutashabihatForWordOrAyah(params: {
  surahId?: number;
  ayahNumber?: number;
  wordText?: string;
  ayahText?: string;
  query?: string;
}): MutashabihatEntry[] {
  const { surahId, ayahNumber, wordText, ayahText, query } = params;
  const normQuery = query ? normalizeQuranicText(query) : '';
  const normWord = wordText ? normalizeQuranicText(wordText) : '';
  const stemWord = normWord ? stripArabicPrefix(normWord) : '';
  const normAyah = ayahText ? normalizeQuranicText(ayahText) : '';

  const isMeaningfulWord =
    normWord.length >= 3 &&
    !ARABIC_STOP_WORDS.has(normWord) &&
    !ARABIC_STOP_WORDS.has(stemWord);

  const scored: { entry: MutashabihatEntry; score: number }[] = [];

  for (const entry of MUTASHABIHAT_DB) {
    let score = 0;

    const normSnippet = normalizeQuranicText(entry.ayahSnippet);
    const normSimilarSnippet = normalizeQuranicText(entry.similarSnippet);
    const normDabit = normalizeQuranicText(entry.dabitRule);
    const normSurah = normalizeQuranicText(entry.surahName);
    const normSimSurah = normalizeQuranicText(entry.similarSurahName);
    const normKeywords = (entry.keywords || []).map(normalizeQuranicText);

    // 1. Free-text query search mode
    if (normQuery) {
      const qTokens = normQuery.split(' ').filter(Boolean);
      const fullHaystack = `${normSurah} ${normSimSurah} ${normSnippet} ${normSimilarSnippet} ${normDabit} ${normKeywords.join(' ')}`;
      if (fullHaystack.includes(normQuery)) {
        score += 100;
      } else {
        const matchedTokens = qTokens.filter((tok) => {
          const stemTok = stripArabicPrefix(tok);
          return (
            fullHaystack.includes(tok) ||
            (stemTok.length >= 3 && fullHaystack.includes(stemTok))
          );
        });
        if (matchedTokens.length > 0) {
          score += matchedTokens.length * 35;
        }
      }
      if (score > 0) {
        scored.push({ entry, score });
      }
      continue;
    }

    // 2. Exact Surah + Ayah match
    if (
      surahId !== undefined &&
      ayahNumber !== undefined &&
      ((entry.surahId === surahId && entry.ayahNumber === ayahNumber) ||
        (entry.similarSurahId === surahId &&
          entry.similarAyahNumber === ayahNumber))
    ) {
      score += 120;
    }

    // 3. Word-level smart match (keywords or snippet words)
    if (isMeaningfulWord) {
      const snippetWords = `${normSnippet} ${normSimilarSnippet}`
        .split(' ')
        .filter(Boolean);
      const exactKeywordHit = normKeywords.some(
        (kw) =>
          kw === normWord ||
          stripArabicPrefix(kw) === stemWord ||
          (stemWord.length >= 4 && kw.includes(stemWord))
      );
      const snippetWordHit = snippetWords.some((sw) => {
        const swStem = stripArabicPrefix(sw);
        return (
          sw === normWord ||
          (stemWord.length >= 3 && swStem === stemWord)
        );
      });

      if (exactKeywordHit) {
        score += entry.surahId === surahId ? 95 : 70;
      } else if (snippetWordHit) {
        score += entry.surahId === surahId ? 80 : 55;
      }
    }

    // 4. Ayah-level phrase overlap when checking a full verse
    if (normAyah && !wordText) {
      const ayahTokens = normAyah
        .split(' ')
        .filter((w) => w.length >= 3 && !ARABIC_STOP_WORDS.has(w));
      const snippetTokens = new Set(
        `${normSnippet} ${normSimilarSnippet}`
          .split(' ')
          .map(stripArabicPrefix)
      );
      let overlap = 0;
      for (const tok of ayahTokens) {
        if (snippetTokens.has(stripArabicPrefix(tok))) {
          overlap++;
        }
      }
      if (overlap >= 3) {
        score += overlap * 20;
      }
    }

    if (score > 0) {
      scored.push({ entry, score });
    }
  }

  return scored
    .sort((a, b) => b.score - a.score)
    .map((item) => item.entry);
}


export interface StudentBadge {
  id: string;
  title: string;
  icon: string;
  colorClass: string;
}

export interface StudentLeaderboardEntry {
  student: Student;
  points: number;
  attendedCount: number;
  avgMastery: number;
  juzCount: number;
  surahCount: number;
  badges: StudentBadge[];
}

export function computeStudentGamification(
  students: Student[],
  sessions: SessionRecord[]
): StudentLeaderboardEntry[] {
  return students
    .map((student) => {
      const stSessions = sessions.filter((s) => s.studentId === student.id);
      const attended = stSessions.filter((s) => s.status === 'حضر');
      const avgMastery =
        attended.length > 0
          ? Math.round(
              attended.reduce((acc, s) => acc + s.masteryScore, 0) / attended.length
            )
          : 92;

      const juzCount = student.memorizedJuz.length;
      const surahCount = student.memorizedSurahs.length;

      // Points calculation: Juz * 150 + Surahs * 25 + Attended * 20 + MasteryBonus
      const points =
        juzCount * 150 +
        surahCount * 25 +
        attended.length * 20 +
        Math.round(avgMastery * 1.5);

      const badges: StudentBadge[] = [];
      if (avgMastery >= 94) {
        badges.push({
          id: 'golden_mastery',
          title: 'وسام الإتقان الذهبي',
          icon: '🏅',
          colorClass: 'bg-amber-100 text-amber-800 dark:bg-amber-950/80 dark:text-amber-300',
        });
      }
      if (attended.length >= 2) {
        badges.push({
          id: 'attendance_star',
          title: 'وسام المواظبة والهمة',
          icon: '⭐',
          colorClass: 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950/80 dark:text-emerald-300',
        });
      }
      if (student.memorizedJuz.includes(30)) {
        badges.push({
          id: 'juz_amma',
          title: 'خاتم جزء عمّ',
          icon: '📖',
          colorClass: 'bg-blue-100 text-blue-800 dark:bg-blue-950/80 dark:text-blue-300',
        });
      }
      if (juzCount >= 10) {
        badges.push({
          id: 'hafiz_knight',
          title: 'فارس العشر الأجزاء',
          icon: '👑',
          colorClass: 'bg-purple-100 text-purple-800 dark:bg-purple-950/80 dark:text-purple-300',
        });
      }

      return {
        student,
        points,
        attendedCount: attended.length,
        avgMastery,
        juzCount,
        surahCount,
        badges,
      };
    })
    .sort((a, b) => b.points - a.points);
}
